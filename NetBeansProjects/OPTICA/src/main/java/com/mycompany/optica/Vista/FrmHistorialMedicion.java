    private void cargarMediciones(){
        try{
            MedicionDAO dao = new MedicionDAO();
            ArrayList<Medicion> lista = dao.listarTodas();
            DefaultTableModel tabla = (DefaultTableModel) jTable1.getModel();
            tabla.setRowCount(0);
            for(Medicion med : lista){
                Object[] fila = {med.getIdMedicion(), med.getIdCliente(), med.getEsfera(), med.getCilindro(), med.getEje(), med.getAdicion()};
                tabla.addRow(fila);
            }
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, ".-.error al cargar mediciones.-." + e.getMessage());
        }
    }

