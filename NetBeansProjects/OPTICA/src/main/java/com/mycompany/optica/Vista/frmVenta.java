    private void btnRegistrarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarVentaActionPerformed
       
            Venta venta = new Venta();

            venta.setClienteId(
                Integer.parseInt(txtIdCliente.getText())
            );

            venta.setSubtotal(
                Double.parseDouble(txtSubtotal.getText())
            );

            venta.setImpuesto(
                Double.parseDouble(txtImpuesto.getText())
            );

            venta.setTotal(
                Double.parseDouble(txtTotal.getText())
            );

            VentaDAO dao = new VentaDAOImpl();

            int idProducto =
                Integer.parseInt(txtIdProducto.getText());

            int cantidad =
                Integer.parseInt(txtCantidad.getText());

            productoDAO daoProducto =
                new productoDAOImpl();

            if(dao.registrarVenta(venta)) {
                DetalleVenta detalle = new DetalleVenta();
            
            detalle.setVentaId(1); // temporal

            detalle.setClienteId(
                Integer.parseInt(
                    txtIdCliente.getText()
            )
        );

            detalle.setProductoId(
                Integer.parseInt(
                    txtIdProducto.getText()
            )
        );

            detalle.setMedicionId(
                Integer.parseInt(
                    txtIdMedicion.getText()
            )
        );

             boolean detalleGuardado = dao.registrarDetalle(detalle);

                if(detalleGuardado){

                    System.out.println(
                        "Detalle registrado correctamente"
          );

            } else {

                    System.out.println(
                        "No se pudo registrar el detalle"
           );
    }
                
                daoProducto.actualizarStock(
                    idProducto,
                    cantidad
            );

                producto p =
                    daoProducto.buscarPorId(
                            idProducto
                    );

                JOptionPane.showMessageDialog(
                        this,
                        "Venta registrada correctamente"
                );

            if(p != null && p.getStock() < 5){

                JOptionPane.showMessageDialog(
                        this,
                        "*** STOCK BAJO ***\n\n" +
                        "Producto: " +
                        p.getNombre() +
                        "\nStock disponible: " +
                        p.getStock()
                );
            }

            } else {

                JOptionPane.showMessageDialog(
                    this,
                    "Error al registrar venta"
            );
        }
    }//GEN-LAST:event_btnRegistrarVentaActionPerformed

