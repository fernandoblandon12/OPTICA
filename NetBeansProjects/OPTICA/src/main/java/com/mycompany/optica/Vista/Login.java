    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
 String usuario = txtUsuario.getText();
    String contraseña = new String(txtPassword.getPassword());

    UsuarioDAO dao = new UsuarioDAO();
    Usuarios encontrado = dao.buscarUsuario(usuario);

    if (encontrado != null &&
        PasswordUtilidades.verificarPassword(
            contraseña, encontrado.getPassword_hash())) {

      
  int rol = encontrado.getId_rol();
      if (rol == 1) {

    // Abrir formulario de Cliente
    FrmRegistroCliente formulario = new FrmRegistroCliente();
    formulario.setVisible(true);
    this.dispose();

} else if (rol == 2) {

    // Abrir formulario de Vendedor
    frmVenta formulario = new frmVenta();
    formulario.setVisible(true);
    this.dispose();

} else {
    JOptionPane.showMessageDialog(this, "Rol no válido");
}
    } else {
    JOptionPane.showMessageDialog(this, "Usuario o contraseña incorrectos");
}
        
    }//GEN-LAST:event_btnIniciarActionPerformed

